create table if not exists public.notification_settings (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  daily_question_reminder boolean not null default true,
  partner_answered boolean not null default true,
  new_memory_added boolean not null default true,
  new_date_idea_added boolean not null default true,
  streak_reminder boolean not null default true,
  reminder_time time not null default '20:00',
  timezone text not null default 'UTC',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
