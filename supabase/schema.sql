alter table public.couple_members enable row level security;
alter table public.questions enable row level security;
alter table public.game_sessions enable row level security;
alter table public.answers enable row level security;
alter table public.memories enable row level security;
alter table public.date_ideas enable row level security;
alter table public.awards enable row level security;


create or replace function public.is_couple_member(target_couple_id uuid, target_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.couple_members cm
    where cm.couple_id = target_couple_id
      and cm.user_id = target_user_id
  );
$$;

create or replace function public.is_couple_owner(target_couple_id uuid, target_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.couple_members cm
    where cm.couple_id = target_couple_id
      and cm.user_id = target_user_id
      and cm.role = 'owner'
  );
$$;


create or replace function public.can_access_session(target_session_id uuid, target_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.game_sessions gs
    join public.couple_members cm on cm.couple_id = gs.couple_id
    where gs.id = target_session_id
      and cm.user_id = target_user_id
  );
$$;

create policy "Profiles are visible to their owner" on public.profiles for select using (auth.uid() = id);
create policy "Profiles can update themselves" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "Questions are readable by authenticated users" on public.questions for select to authenticated using (is_active = true);

create policy "Couple members can read their couples" on public.couples for select using (public.is_couple_member(id));
create policy "Authenticated users can create couples" on public.couples for insert to authenticated with check (created_by = auth.uid());
create policy "Couple owners can update couples" on public.couples for update using (public.is_couple_owner(id));

create policy "Members can read memberships" on public.couple_members for select using (public.is_couple_member(couple_id));
create policy "Users can join themselves" on public.couple_members for insert to authenticated with check (user_id = auth.uid());

create policy "Members can manage sessions" on public.game_sessions for all using (public.is_couple_member(couple_id)) with check (public.is_couple_member(couple_id));
create policy "Members can manage answers" on public.answers for all using (public.can_access_session(session_id)) with check (user_id = auth.uid());
create policy "Members can manage memories" on public.memories for all using (public.is_couple_member(couple_id)) with check (public.is_couple_member(couple_id));
create policy "Members can manage date ideas" on public.date_ideas for all using (public.is_couple_member(couple_id)) with check (public.is_couple_member(couple_id));
create policy "Members can manage awards" on public.awards for all using (public.is_couple_member(couple_id)) with check (public.is_couple_member(couple_id));
