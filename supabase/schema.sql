-- OurStory production schema for Supabase Postgres.
-- Run this in the Supabase SQL editor after creating the project.

create extension if not exists "pgcrypto";

create type public.couple_role as enum ('owner', 'partner');
create type public.game_type as enum ('question_jar', 'memory_lane', 'date_spark', 'love_awards');
create type public.session_status as enum ('draft', 'active', 'revealed', 'archived');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.couples (
  id uuid primary key default gen_random_uuid(),
  name text not null default 'Our Story',
  invite_code text not null unique default upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 10)),
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.couple_members (
  couple_id uuid not null references public.couples(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role public.couple_role not null default 'partner',
  joined_at timestamptz not null default now(),
  primary key (couple_id, user_id)
);

create table public.questions (
  id bigint generated by default as identity primary key,
  category text not null,
  mood text not null,
  prompt text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  couple_id uuid not null references public.couples(id) on delete cascade,
  game_type public.game_type not null,
  status public.session_status not null default 'draft',
  title text,
  metadata jsonb not null default '{}'::jsonb,
  current_question_id bigint references public.questions(id),
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  revealed_at timestamptz,
  archived_at timestamptz
);

create table public.answers (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  question_id bigint references public.questions(id),
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (session_id, user_id)
);

create table public.memories (
  id uuid primary key default gen_random_uuid(),
  couple_id uuid not null references public.couples(id) on delete cascade,
  title text not null,
  body text,
  happened_on date,
  emotion text,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.date_ideas (
  id uuid primary key default gen_random_uuid(),
  couple_id uuid not null references public.couples(id) on delete cascade,
  title text not null,
  description text not null,
  budget text,
  energy text,
  scheduled_for timestamptz,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.awards (
  id uuid primary key default gen_random_uuid(),
  couple_id uuid not null references public.couples(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  note text not null,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_touch_updated_at before update on public.profiles for each row execute function public.touch_updated_at();
create trigger couples_touch_updated_at before update on public.couples for each row execute function public.touch_updated_at();
create trigger answers_touch_updated_at before update on public.answers for each row execute function public.touch_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, avatar_url)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)), new.raw_user_meta_data ->> 'avatar_url')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();


create or replace function public.handle_new_couple()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.couple_members (couple_id, user_id, role)
  values (new.id, new.created_by, 'owner')
  on conflict (couple_id, user_id) do nothing;
  return new;
end;
$$;

create trigger on_couple_created after insert on public.couples for each row execute function public.handle_new_couple();

